#!/usr/bin/env bash
# Builds every asset of the Host CLI in build/host-cli: the muxify CLI as static
# (musl) Linux binaries for aarch64 and x86_64, muxify-linux-<arch>, built in
# Docker with the Swift Static Linux SDK; muxify-darwin-arm64, a release
# swift build on the Mac; version, the line that their --version prints; and
# install.sh, the install script that the app runs and the phone fetches.
# One container cross-compiles both architectures. The SDK, the package cache
# and the Linux build folder stay in a Docker volume, apart from the Mac's .build,
# so a second run only rebuilds what changed.
#
# The argument picks the part: linux (make host-cli-linux) needs only Docker,
# darwin (make host-cli-darwin) only the Mac's Swift, so CI builds each on its
# own runner; none builds both (make host-cli). Every part writes the same
# version line.
set -euo pipefail

PART="${1:-all}"
case "$PART" in
  all|linux|darwin) ;;
  *) echo "usage: $0 [linux|darwin]" >&2; exit 2 ;;
esac

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=host-cli-version.env
source "$ROOT/scripts/host-cli-version.env"
CACHE_VOLUME="${HOST_CLI_CACHE_VOLUME:-muxify-host-cli-cache}"
OUT=build/host-cli

if [ "$PART" != darwin ]; then
  command -v docker >/dev/null || { echo "make host-cli-linux needs Docker (OrbStack on a Mac)" >&2; exit 1; }
fi
mkdir -p "$ROOT/$OUT"

# Every binary carries one stamp: the commit and its committer time in Unix
# seconds. The generated source is ignored by git and removed after the build,
# so a plain swift build and the Xcode build stay `dev 0`.
VERSION="muxify $(git -C "$ROOT" rev-parse --short HEAD) $(git -C "$ROOT" log -1 --format=%ct)"
STAMP_SOURCE="$ROOT/Sources/MuxifyCLI/BuildStamp+Generated.swift"
trap 'rm -f "$STAMP_SOURCE"' EXIT
cat >"$STAMP_SOURCE" <<SWIFT
// Generated by scripts/build-host-cli.sh for make host-cli. Git ignores this file.
extension BuildStamp: StampedBuild {
    static let stamp = "${VERSION#muxify }"
}
SWIFT

if [ "$PART" != darwin ]; then
  docker run --rm \
    -v "$ROOT:/src" -v "$CACHE_VOLUME:/cache" -w /src \
    -e HOME=/cache/home \
    -e SDK_URL="$HOST_CLI_SDK_URL" -e SDK_SHA256="$HOST_CLI_SDK_SHA256" \
    -e OUT="$OUT" -e VERSION="$VERSION" -e OWNER="$(id -u):$(id -g)" \
    "$HOST_CLI_SWIFT_IMAGE" bash -euo pipefail -c '
      sdks=/cache/swift-sdks
      mkdir -p "$HOME" "$sdks"
      if ! swift sdk list --swift-sdks-path "$sdks" 2>/dev/null | grep -q static-linux; then
        swift sdk install "$SDK_URL" --checksum "$SDK_SHA256" --swift-sdks-path "$sdks"
      fi
      for arch in aarch64 x86_64; do
        scratch="/cache/build/$arch"
        swift build -c release --product muxify --swift-sdks-path "$sdks" \
          --swift-sdk "$arch-swift-linux-musl" --scratch-path "$scratch" \
          -Xlinker -s
        install -m 0755 "$scratch/release/muxify" "$OUT/muxify-linux-$arch"
        chown "$OWNER" "$OUT/muxify-linux-$arch"
      done
      # The binary for the container architecture runs here.
      printed="$("$OUT/muxify-linux-$(uname -m)" --version)"
      [ "$printed" = "$VERSION" ] || { echo "muxify-linux-$(uname -m) --version printed \"$printed\", not \"$VERSION\"" >&2; exit 1; }
    '
fi

cd "$ROOT"
if [ "$PART" != linux ]; then
  swift build -c release --product muxify --arch arm64
  install -m 0755 "$(swift build -c release --product muxify --arch arm64 --show-bin-path)/muxify" "$OUT/muxify-darwin-arm64"
  printed="$("$OUT/muxify-darwin-arm64" --version)"
  [ "$printed" = "$VERSION" ] || { echo "muxify-darwin-arm64 --version printed '$printed', not '$VERSION'" >&2; exit 1; }
fi
printf '%s\n' "$VERSION" >"$OUT/version"
# The app's own copy of the script, byte for byte (ADR 0076).
cp "$ROOT/Packages/MuxifyCore/Sources/MuxifyCore/Environment/host-cli-install.sh" "$OUT/install.sh"
ls -l "$OUT"
